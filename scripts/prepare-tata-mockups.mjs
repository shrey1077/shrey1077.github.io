/**
 * prepare-tata-mockups.mjs — the resting image for every work tile.
 *
 * A tile shows a MOCKUP at rest and the flat artwork only once you hover it,
 * so every subsection needs one staged image on white. Two sources, in order
 * of trust:
 *
 *  1. The site owner's own Photoshop mockups, sitting unused in
 *     `D:\Brain Website portfolio\Tata\portfolio shrey\`. These are real
 *     composites with correct perspective and lighting — always preferred.
 *  2. `Digital/Mockups/**` in the archive, already themed and imported by
 *     prepare-tata-themes.mjs.
 *
 * Anything still uncovered is generated by `make-studio-mockups.mjs`, which
 * composites the real artwork into an accurate product shot rather than
 * inventing a scene.
 *
 * Output naming is the contract the page reads:
 *   mockup-<name>.webp   → staged; a tile prefers this at rest
 *   installed-<name>.webp → a real photograph of the thing in place (better)
 *
 * Backgrounds are flattened to pure white, since the tile stage is white and
 * a grey studio card reads as a dirty rectangle against it.
 *
 * Idempotent. Run: node scripts/prepare-tata-mockups.mjs
 */

import sharp from "sharp";
import fs from "node:fs";
import path from "node:path";

const PS = "D:/Brain Website portfolio/Tata/portfolio shrey";
const FOLIO = "D:/Brain Website portfolio/Tata folio/Graphics/Mockups";
const DEST = "D:/Brain Folio/public/content/clients/tata-iis/catalogue";

const MAX_W = 1600;

/** [source file, catalogue folder, output stem].
 *  Chosen so no mockup carries a real trainee's name — the certificate
 *  template reads "Lorem Singh Ipsum" and the visiting card is the designer's
 *  own. */
const IMPORTS = [
  [`${PS}/01 - Certificate Mockup.png`, "Certificates", "mockup-certificate-framed"],
  [`${PS}/existvc.png`, "Visiting Cards", "mockup-visiting-card-holder"],
  [`${PS}/Bookmark Mockup.png`, "Stickers & Notepads", "mockup-bookmarks-gdt"],
  [`${PS}/Bookmark Mockup3.png`, "Stickers & Notepads", "mockup-bookmarks-campaign"],
  [`${PS}/Flyer Mockup.png`, "Flyers & Campaigns", "mockup-flyers-pair"],
  [`${PS}/19.png`, "Campus Posters", "mockup-programs-poster"],
  [`${PS}/FundingOG.png`, "Trifolds", "mockup-funding-trifold"],
  [`${PS}/4.png`, "Brochures", "mockup-brochure-spread"],
  [`${FOLIO}/Exterior Gate TATA IIS A.png`, "Billboards & Signages", "iisa-mockup-exterior-gate"],
  [`${FOLIO}/Exterior Gate TATA IIS M.png`, "Billboards & Signages", "iism-mockup-exterior-gate"],
];

/** Flatten onto white and trim any uniform border the mockup was exported with. */
async function importOne(src, folder, stem) {
  const outDir = path.join(DEST, folder);
  fs.mkdirSync(outDir, { recursive: true });
  const out = path.join(outDir, `${stem}.webp`);

  await sharp(src)
    .flatten({ background: "#ffffff" })
    .trim({ threshold: 6 })
    .resize({ width: MAX_W, withoutEnlargement: true })
    // A hair of white margin so the subject never touches the tile edge.
    .extend({ top: 24, bottom: 24, left: 24, right: 24, background: "#ffffff" })
    .webp({ quality: 86 })
    .toFile(out);

  return fs.statSync(out).size;
}

let n = 0, bytes = 0;
const missing = [];

for (const [src, folder, stem] of IMPORTS) {
  if (!fs.existsSync(src)) { missing.push(path.basename(src)); continue; }
  try {
    const size = await importOne(src, folder, stem);
    bytes += size; n++;
    console.log(`  ${folder.padEnd(22)} ${stem}  ${Math.round(size / 1024)} KB`);
  } catch (err) {
    missing.push(`${path.basename(src)} (${err.message.slice(0, 50)})`);
  }
}

console.log(`\n${n} owner mockups imported (${(bytes / 1048576).toFixed(1)} MB)`);
if (missing.length) {
  console.log(`\n${missing.length} missing/failed:`);
  for (const m of missing) console.log("  -", m);
}
