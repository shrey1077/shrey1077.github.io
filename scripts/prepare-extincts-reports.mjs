/**
 * prepare-extincts-reports.mjs — the Extincts Project's three research reports,
 * page by page, for the Extincts room's "Initial Research" (owner, 2026-10-03).
 *
 *   _source/BWP/Extincts/reports/report-N.pdf   (gitignored originals)
 *   → public/content/extincts/reports/report-N/NN.webp
 *   → src/constants/extinctsReportPages.ts       (generated: urls + sizes)
 *
 * The originals were copied from the owner's archive on 2026-10-03:
 *   report-1  Graduation Project The Extincts/fin1/First Report The Extincts Shrey Singh.pdf
 *             (Feb 2020 — the problem, the literature, the field trips; 29 pp)
 *   report-2  Graduation Project The Extincts/Report2/REPORT2Submission-Shrey Singh.pdf
 *             (Apr 2020 — "Part 2: Approaching the story"; 17 pp)
 *   report-3  Graduation Project The Extincts/REport3/Final Report 3.pdf
 *             (May 2020 — the final graduation document; 78 pp)
 * All three are also on the owner's Drive under the same names.
 *
 * ENGINE: pdf-to-img (pdfjs). The repo's PDFium shim (pdf-to-images.mjs) needs
 * a Python this machine does not have; these are ordinary A4/Letter pages,
 * which pdfjs renders without trouble.
 *
 *   node scripts/prepare-extincts-reports.mjs
 */

import { pdf } from "pdf-to-img";
import sharp from "sharp";
import fs from "node:fs";
import path from "node:path";
import { BWP, CONTENT, ROOT } from "./sources.mjs";

const SRC = path.join(BWP, "Extincts", "reports");
const OUT = path.join(CONTENT, "extincts", "reports");
const TS = path.join(ROOT, "src", "constants", "extinctsReportPages.ts");
const REPORTS = ["report-1", "report-2", "report-3"];
/** Long edge of a page, px — reads sharp at a reader's ~1000px column. */
const MAX_EDGE = 1600;
const QUALITY = 80;

const manifest = {};
for (const id of REPORTS) {
  const dir = path.join(OUT, id);
  fs.rmSync(dir, { recursive: true, force: true });
  fs.mkdirSync(dir, { recursive: true });
  const doc = await pdf(path.join(SRC, `${id}.pdf`), { scale: 2.4 });
  const pages = [];
  let n = 0;
  let bytes = 0;
  for await (const png of doc) {
    n++;
    const name = `${String(n).padStart(2, "0")}.webp`;
    const meta = await sharp(png)
      .resize({ width: MAX_EDGE, height: MAX_EDGE, fit: "inside", withoutEnlargement: true })
      .webp({ quality: QUALITY })
      .toFile(path.join(dir, name));
    bytes += meta.size;
    pages.push({ src: `/content/extincts/reports/${id}/${name}`, w: meta.width, h: meta.height });
  }
  manifest[id] = pages;
  console.log(`${id}: ${n} pages, ${(bytes / 1048576).toFixed(1)}MB`);
}

const body = Object.entries(manifest)
  .map(
    ([id, pages]) =>
      `  "${id}": [\n${pages.map((p) => `    { src: "${p.src}", w: ${p.w}, h: ${p.h} },`).join("\n")}\n  ],`,
  )
  .join("\n");
fs.writeFileSync(
  TS,
  `/**
 * extinctsReportPages — GENERATED by scripts/prepare-extincts-reports.mjs; do
 * not edit by hand. Every page of the three Extincts research reports, with
 * its size, for the room's reader.
 */

export interface ReportPage {
  src: string;
  w: number;
  h: number;
}

export const EXTINCTS_REPORT_PAGES: Record<string, ReportPage[]> = {
${body}
};
`,
);
console.log(`wrote ${path.relative(ROOT, TS)}`);
