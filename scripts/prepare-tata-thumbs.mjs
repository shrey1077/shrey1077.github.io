/**
 * prepare-tata-thumbs.mjs — small copies of the Tata IIS work, for the walls
 * and strips the page shows it in (2026-10-05).
 *
 * The page lays nearly all of the work open at once now — the mockups on a
 * moving wall, Print as sixteen tiles that turn through their pieces, the
 * installed work, the screens — and every one of those is a few hundred
 * pixels across. The catalogue's files are up to 1800px and ~200KB each, so
 * the walls take these instead and the full file loads only in the viewer.
 *
 *   public/content/clients/tata-iis/catalogue/<Folder>/<file>
 *   public/content/clients/tata-iis/reality/<file>
 *   public/content/clients/tata-iis/brand/guidelines{,-iisa,-iism}/<file>  (the rulebooks)
 *   → public/content/clients/tata-iis/thumbs/<folder-id>/<name>.webp
 *   → src/constants/tataThumbs.ts                         (generated)
 *
 * The manifest is keyed by the ORIGINAL file's url, exactly as the catalogue
 * reader builds it, and carries the original's size too — so a layout can
 * size a tile to its picture without opening the file. A file with no entry
 * (added since this last ran) simply shows full size; re-run to catch up.
 * Only files that are new or newer than their thumbnail are re-encoded.
 *
 *   node scripts/prepare-tata-thumbs.mjs
 */

import sharp from "sharp";
import fs from "node:fs";
import path from "node:path";
import { ROOT } from "./sources.mjs";

const TATA = path.join(ROOT, "public/content/clients/tata-iis");
const OUT = path.join(TATA, "thumbs");
const TS = path.join(ROOT, "src/constants/tataThumbs.ts");
/** The long side, px. The largest wall tile is ~300 CSS px; this covers it
 *  at 2× without carrying the full file. */
const LONG = 640;
const IMAGE = /\.(webp|jpe?g|png)$/i;

/** The url the catalogue reader would give this file (src/content/catalogue.ts). */
const url = (...segs) => "/" + segs.map(encodeURIComponent).join("/");
/** catalogue.ts's folderToId. */
const idOf = (name) =>
  name.toLowerCase().replace(/&/g, "and").replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");
const visible = (name) => !name.startsWith(".") && !name.startsWith("_");

/** [source path, its url segments under /content, the thumb's folder id]. */
const jobs = [];
for (const folder of fs.readdirSync(path.join(TATA, "catalogue")).filter(visible)) {
  const dir = path.join(TATA, "catalogue", folder);
  if (!fs.statSync(dir).isDirectory()) continue;
  for (const file of fs.readdirSync(dir).filter((f) => visible(f) && IMAGE.test(f))) {
    jobs.push([path.join(dir, file), ["catalogue", folder, file], idOf(folder)]);
  }
}
for (const file of fs.readdirSync(path.join(TATA, "reality")).filter((f) => visible(f) && IMAGE.test(f))) {
  jobs.push([path.join(TATA, "reality", file), ["reality", file], "reality"]);
}
// The three rulebooks' plates, for band 02's decks.
for (const book of ["guidelines", "guidelines-iisa", "guidelines-iism"]) {
  for (const file of fs.readdirSync(path.join(TATA, "brand", book)).filter((f) => visible(f) && IMAGE.test(f))) {
    jobs.push([path.join(TATA, "brand", book, file), ["brand", book, file], book]);
  }
}

const manifest = {};
let made = 0;
for (const [src, segs, id] of jobs) {
  const name = path.parse(segs.at(-1)).name;
  const out = path.join(OUT, id, `${name}.webp`);
  const meta = await sharp(src).metadata();
  // Sizes as displayed: EXIF orientations 5–8 swap the axes.
  const turned = (meta.orientation ?? 1) >= 5;
  const w = turned ? meta.height : meta.width;
  const h = turned ? meta.width : meta.height;
  if (!fs.existsSync(out) || fs.statSync(out).mtimeMs < fs.statSync(src).mtimeMs) {
    fs.mkdirSync(path.dirname(out), { recursive: true });
    await sharp(src)
      .rotate()
      .resize(LONG, LONG, { fit: "inside", withoutEnlargement: true })
      .webp({ quality: 74 })
      .toFile(out);
    made++;
  }
  manifest[url("content", "clients", "tata-iis", ...segs)] = {
    src: url("content", "clients", "tata-iis", "thumbs", id, `${name}.webp`),
    w,
    h,
  };
}

const body = `/**
 * GENERATED by scripts/prepare-tata-thumbs.mjs — do not edit by hand.
 *
 * Every Tata IIS catalogue and installed-work image, keyed by its url: a
 * ${LONG}px thumbnail for the page's walls, and the original's size.
 * ⚠ Server-side only — it is large. The page resolves what it needs and
 * hands its client components plain plates.
 */

export interface TataThumb {
  src: string;
  w: number;
  h: number;
}

export const TATA_THUMBS: Record<string, TataThumb> = ${JSON.stringify(manifest, null, 2)};
`;
fs.writeFileSync(TS, body);
console.log(`${jobs.length} images, ${made} thumbnails written → ${path.relative(ROOT, TS)}`);
