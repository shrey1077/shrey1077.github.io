import sharp from "sharp";
import fs from "node:fs";
import path from "node:path";
import { ASSETS, CONTENT, ROOT } from "./sources.mjs";

const SRC = path.join(ASSETS, "Clients/Tata IIS/Digital");
const OUT = path.join(CONTENT, "clients/tata-iis/tools");
const TS = path.join(ROOT, "src/constants/tataTools.ts");
const URL = "/content/clients/tata-iis/tools";

const FULL_W = 2400;
const THUMB_W = 960;

/** Each tool's folder, and what each of its shots shows, in order. */
const TOOLS = {
  cerci: {
    folder: "Cerci v2.7",
    names: {
      "cerci-v2.7-01-iis-ahmedabad": "IIS Ahmedabad theme",
      "cerci-v2.7-02-iis-mumbai": "IIS Mumbai theme",
      "cerci-v2.7-03-tata-iis": "Tata IIS theme",
      "cerci-v2.7-04-godrej-template": "A brand template — Godrej",
      "cerci-v2.7-05-iis-mumbai-dark": "Dark mode",
    },
  },
  h3len: {
    folder: "H3LEN",
    names: {
      "h3len-01-campus": "The Ahmedabad campus, on load",
      "h3len-02-tour": "Mid-tour",
    },
  },
};

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(path.join(OUT, "thumbs"), { recursive: true });

const shots = {};
for (const [tool, { folder, names }] of Object.entries(TOOLS)) {
  shots[tool] = [];
  for (const [base, name] of Object.entries(names)) {
    const src = path.join(SRC, folder, `${base}.png`);
    const full = await sharp(src).resize({ width: FULL_W }).webp({ quality: 84 }).toFile(path.join(OUT, `${base}.webp`));
    const thumb = await sharp(src).resize({ width: THUMB_W }).webp({ quality: 80 }).toFile(path.join(OUT, "thumbs", `${base}.webp`));
    shots[tool].push({
      url: `${URL}/${base}.webp`,
      thumb: `${URL}/thumbs/${base}.webp`,
      name,
      w: full.width,
      h: full.height,
    });
    console.log(base, full.width, "x", full.height, Math.round(full.size / 1024) + "KB", "thumb", Math.round(thumb.size / 1024) + "KB");
  }
}

const ts = `/**
 * GENERATED by scripts/prepare-tata-tools.mjs — do not edit by hand.
 *
 * Band 08's AI Solutions: screenshots of the tools, as plates (full file,
 * thumbnail, what it shows, the full file's size).
 */

import type { TataPlate } from "@/components/client/tata/TataViewer";

export const TATA_TOOL_SHOTS: Record<"cerci" | "h3len", readonly TataPlate[]> = ${JSON.stringify(shots, null, 2)};
`;
fs.writeFileSync(TS, ts);
console.log("wrote", path.relative(ROOT, TS));
